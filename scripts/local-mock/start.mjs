// One command for local host testing without Docker.
//
//   1. writes .env.local pointing at the mock backend,
//   2. starts the mock API (auth + REST + Edge Function proxy),
//   3. starts the real Edge Functions in a Deno child process,
//   4. starts `npm run dev` (Vite).
//
// Ctrl+C stops everything.

import { spawn } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PORT, FUNCTIONS_PORT, keys } from './config.mjs';
import { startMockServer } from './server.mjs';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const ENV_PATH = `${ROOT}.env.local`;
const { anonKey, serviceKey } = keys();

const envContent = [
    '# Generated by `npm run local` (scripts/local-mock/start.mjs). LOCAL ONLY.',
    `VITE_SUPABASE_URL=http://127.0.0.1:${PORT}`,
    `VITE_SUPABASE_ANON_KEY=${anonKey}`,
    '',
    '# Patient attachments need a Cloudinary account (optional).',
    'VITE_CLOUDINARY_CLOUD_NAME=',
    'VITE_CLOUDINARY_UPLOAD_PRESET=',
    'VITE_CLOUDINARY_AUTHENTICATED=false',
    '',
].join('\n');

const current = existsSync(ENV_PATH) ? readFileSync(ENV_PATH, 'utf8') : '';
if (current !== envContent) {
    if (current) copyFileSync(ENV_PATH, `${ENV_PATH}.bak`);
    writeFileSync(ENV_PATH, envContent);
    console.log('[mock] wrote .env.local');
}

function spawnChild(command, args, options = {}) {
    const child = spawn(command, args, { stdio: 'inherit', ...options });
    child.on('error', (error) => console.error(`[mock] failed to start ${command}:`, error.message));
    return child;
}

const children = [];

// The real Edge Functions (login, ai-settings, manage-user, import-job, ...).
const deno = spawnChild('deno', [
    'run', '-A', '--no-check',
    `${ROOT}scripts/local-mock/functions-router.ts`,
], {
    cwd: ROOT,
    env: {
        ...process.env,
        MOCK_FUNCTIONS_PORT: String(FUNCTIONS_PORT),
        SUPABASE_URL: `http://127.0.0.1:${PORT}`,
        SUPABASE_ANON_KEY: anonKey,
        SUPABASE_SERVICE_ROLE_KEY: serviceKey,
        AI_SETTINGS_ENC_KEY: 'local-dev-only-clinic-ai-settings-key',
        IMPORT_CLEANUP_SECRET: 'local-dev-only-cleanup-secret',
        LOCAL_INFERENCE_ENABLED: '1',
    },
});
children.push(deno);

const server = await startMockServer();

const vite = spawnChild('npm', ['run', 'dev'], { cwd: ROOT, shell: true });
children.push(vite);
console.log('[mock] Vite dev server starting on http://localhost:3000');

let stopping = false;
function stop() {
    if (stopping) return;
    stopping = true;
    console.log('\n[mock] stopping...');
    for (const child of children) {
        try { child.kill(); } catch { /* already gone */ }
    }
    server.close(() => process.exit(0));
    setTimeout(() => process.exit(0), 1500).unref();
}

process.on('SIGINT', stop);
process.on('SIGTERM', stop);
