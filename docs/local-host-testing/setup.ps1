<#
    Local host testing - one-time setup.

    Starts the local Supabase stack, applies the schema migration and the local
    seed, creates the test login (yossef / 123, Super Admin) and writes
    .env.local so `npm run dev` talks to the local stack and never to the
    hosted project.

    Run from anywhere:
        powershell -ExecutionPolicy Bypass -File docs/local-host-testing/setup.ps1

    Options:
        -SkipStart   the stack is already running (only re-create the login + env)
        -Force       overwrite an existing .env.local without a backup
#>
[CmdletBinding()]
param(
    [switch]$SkipStart,
    [switch]$Force,
    [string]$SupabaseVersion = '2.122.0'
)

$ErrorActionPreference = 'Stop'

$loginUsername = 'yossef'
$loginEmail = 'yossef@clinic.local'
$loginPassword = '123'
$loginName = 'Yossef'

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$envFile = Join-Path $repoRoot '.env.local'

function Write-Step($message) { Write-Host "==> $message" -ForegroundColor Cyan }
function Fail($message) { Write-Host "ERROR: $message" -ForegroundColor Red; exit 1 }

function Supa([string[]]$CommandArgs) {
    & npx --yes "supabase@$SupabaseVersion" @CommandArgs
    if ($LASTEXITCODE -ne 0) { Fail "supabase $($CommandArgs -join ' ') failed (exit $LASTEXITCODE)" }
}

Write-Step "Checking Docker"
$dockerVersion = $null
try { $dockerVersion = (docker info --format '{{.ServerVersion}}' 2>$null) } catch { }
if (-not $dockerVersion) {
    Write-Host "Docker is not running. Start Docker Desktop and wait for 'Engine running'." -ForegroundColor Red
    Write-Host "If docker info still fails on Windows, the Virtual Machine Platform / WSL2"
    Write-Host "feature is missing - see the 'Windows note' in"
    Write-Host "  docs/local-host-testing/README.md"
    exit 1
}
Write-Host "    Docker engine $dockerVersion"

if (-not $SkipStart) {
    Write-Step "Starting the local Supabase stack (first run downloads ~1.5 GB)"
    Push-Location $repoRoot
    try { Supa @('start') } finally { Pop-Location }
}

Write-Step "Reading the local stack status"
Push-Location $repoRoot
try {
    $statusLines = Supa @('status', '-o', 'env')
} finally { Pop-Location }

$status = @{}
foreach ($line in $statusLines) {
    if ($line -match '^([A-Z_]+)="?(.*?)"?$') { $status[$matches[1]] = $matches[2] }
}
$apiUrl = $status['API_URL']
$anonKey = $status['ANON_KEY']
$serviceKey = $status['SERVICE_ROLE_KEY']
if (-not $apiUrl -or -not $anonKey -or -not $serviceKey) {
    Fail "Could not read API_URL / ANON_KEY / SERVICE_ROLE_KEY from 'supabase status'."
}

$headers = @{ apikey = $serviceKey; Authorization = "Bearer $serviceKey" }

Write-Step "Ensuring the test login ($loginUsername / $loginPassword)"
$userId = $null
$createBody = @{
    email = $loginEmail
    password = $loginPassword
    email_confirm = $true
    user_metadata = @{ name = $loginName }
} | ConvertTo-Json -Depth 5

try {
    $created = Invoke-RestMethod -Method Post -Uri "$apiUrl/auth/v1/admin/users" `
        -Headers $headers -ContentType 'application/json' -Body $createBody
    $userId = $created.id
    Write-Host "    created $loginEmail"
} catch {
    $statusCode = 0
    if ($_.Exception.Response) { $statusCode = [int]$_.Exception.Response.StatusCode.value__ }
    if ($statusCode -eq 422 -or $statusCode -eq 409) {
        Write-Host "    $loginEmail already exists"
        $list = Invoke-RestMethod -Method Get -Uri "$apiUrl/auth/v1/admin/users?page=1&per_page=200" -Headers $headers
        $match = @($list.users) | Where-Object { $_.email -eq $loginEmail } | Select-Object -First 1
        if ($match) { $userId = $match.id }
    } else {
        Fail "Could not create the login: $($_.Exception.Message)"
    }
}

if (-not $userId) { Fail "Login $loginEmail was not found after creation." }

Write-Step "Promoting $loginEmail to Super Admin"
$patchBody = @{ name = $loginName; is_super_admin = $true; is_admin = $true } | ConvertTo-Json
$patchHeaders = @{ apikey = $serviceKey; Authorization = "Bearer $serviceKey"; Prefer = 'return=representation' }
Invoke-RestMethod -Method Patch -Uri "$apiUrl/rest/v1/users?id=eq.$userId" `
    -Headers $patchHeaders -ContentType 'application/json' -Body $patchBody | Out-Null
Write-Host "    done"

Write-Step "Writing $envFile"
if ((Test-Path $envFile) -and -not $Force) {
    $backup = "$envFile.bak"
    Copy-Item $envFile $backup -Force
    Write-Host "    existing file backed up to $backup"
}
$envContent = @"
# Generated by docs/local-host-testing/setup.ps1 - LOCAL ONLY, do not commit.
VITE_SUPABASE_URL=$apiUrl
VITE_SUPABASE_ANON_KEY=$anonKey

# Optional: attachments need a Cloudinary account.
VITE_CLOUDINARY_CLOUD_NAME=
VITE_CLOUDINARY_UPLOAD_PRESET=
VITE_CLOUDINARY_AUTHENTICATED=false
"@
Set-Content -Path $envFile -Value $envContent -Encoding UTF8

Write-Host ""
Write-Host "Local stack is ready." -ForegroundColor Green
Write-Host "  Studio : http://127.0.0.1:54323"
Write-Host "  API    : $apiUrl"
Write-Host "  Login  : $loginUsername / $loginPassword"
Write-Host ""
Write-Host "Start the app with:  npm run dev   (then open http://localhost:3000)"
